"use client";
import React, { useCallback, useEffect, useState } from "react";
import { Bell, CheckCheck } from "lucide-react";
import { api, timeAgo, fmtDateTime } from "@/lib/client";
import { Card, EmptyState, PageHead, Spinner } from "@/components/sugam/ui-bits";
import type { NotificationRow } from "@/lib/types";

export function NotificationCenter({ onOpenCase, refreshKey }: { onOpenCase: (id: string) => void; refreshKey: number }) {
  const [rows, setRows] = useState<NotificationRow[] | null>(null);
  const [unread, setUnread] = useState(0);

  const load = useCallback(() => {
    api<{ notifications: NotificationRow[]; unread: number }>("/api/v1/notifications").then((r) => {
      if (r.success) { setRows(r.notifications); setUnread(r.unread); }
    });
  }, []);
  useEffect(() => { load(); }, [load, refreshKey]);

  const markAll = async () => {
    await api("/api/v1/notifications/read", { json: {} });
    load();
  };

  const open = async (n: NotificationRow) => {
    if (!n.readAt) await api("/api/v1/notifications/read", { json: { ids: [n.id] } });
    if (n.caseId) onOpenCase(n.caseId);
    else load();
  };

  const icon: Record<string, string> = {
    DUE_SOON: "◷", OVERDUE: "⚠", ESCALATION: "📢", ASSIGNED: "👤", RESPONSE_REQUESTED: "📣",
    RESPONSE_ADDED: "📨", STATUS_UPDATED: "🔄", REPORT_SENT: "📢", RATE_REQUEST: "⭐",
  };

  return (
    <div>
      <PageHead title="Notifications" subtitle="In-app alerts generated by automation — deduplicated per policy window.">
        {unread > 0 && (
          <button onClick={markAll} className="flex items-center gap-1.5 rounded-lg border border-su-blue/40 bg-white px-3 py-2 text-xs font-bold text-su-blue">
            <CheckCheck className="h-3.5 w-3.5" /> Mark all read ({unread})
          </button>
        )}
      </PageHead>
      {rows === null ? <Spinner /> : rows.length === 0 ? (
        <EmptyState icon={<Bell className="h-10 w-10" />} title="No notifications" hint="Deadline alerts, assignments, responses and reports arrive here." />
      ) : (
        <div className="space-y-2">
          {rows.map((n) => (
            <button key={n.id} onClick={() => open(n)}
              className={`flex w-full items-start gap-3 rounded-lg border p-3.5 text-left transition hover:border-su-blue ${n.readAt ? "border-su-border bg-white" : "border-su-blue/40 bg-su-blue-soft/40"}`}>
              <span className="mt-0.5 text-lg">{icon[n.type] ?? "🔔"}</span>
              <span className="min-w-0 flex-1">
                <span className="flex flex-wrap items-center gap-2">
                  <span className="text-sm font-bold text-su-navy">{n.title}</span>
                  {!n.readAt && <span className="rounded-full bg-su-saffron px-1.5 py-px text-[9px] font-bold uppercase text-white">new</span>}
                </span>
                <span className="mt-0.5 block text-xs leading-relaxed text-su-muted">{n.message}</span>
                <span className="mt-1 block text-[10px] text-su-muted/70">{fmtDateTime(n.createdAt)} · {timeAgo(n.createdAt)}</span>
              </span>
            </button>
          ))}
        </div>
      )}
    </div>
  );
}
